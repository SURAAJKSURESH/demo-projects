// Helper to get relative delivery date strings
export const getTentativeDeliveryDate = (daysFromNow = 3) => {
  const date = new Date();
  date.setDate(date.getDate() + daysFromNow);
  return date.toLocaleDateString('en-US', {
    weekday: 'short',
    month: 'short',
    day: 'numeric',
  });
};

